#!/usr/bin/env python3
"""Generate the Supabase SQL from the app's own data modules.

    python3 scripts/build-supabase-sql.py

Writes supabase/migrations/*.sql and supabase/seed_audits_2025Q4_2026Q1.sql.

The reference data (checklist, issue categories, hazards, disciplines, bands)
is PARSED OUT OF src/lib/ehss/*.ts rather than retyped, so the database and
the app cannot disagree about what a question weighs or what a category
means. Counts are asserted at the end: 81 questions, 13 issue categories,
14 hazards, 5 disciplines, 5 bands, 13 contractors, 19 audits.
"""

import pathlib
import re
import sys

SRC = pathlib.Path("src/lib/ehss")
OUT = pathlib.Path("supabase")


def q(value) -> str:
    """A SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return f"{value:g}"
    return "'" + str(value).replace("'", "''") + "'"


def records(text: str, array_name: str):
    """Every {...} record in an exported array literal, as dicts of raw text."""
    # Skip past the TYPE annotation: `export const DOMAINS: Domain[] = [`
    # has an empty [] before the real array, and scanning from the first
    # bracket finds that one instead.
    start = text.index(f"{array_name}")
    start = text.index("= [", start) + 2
    depth, i = 0, start
    while True:
        if text[i] == "[":
            depth += 1
        elif text[i] == "]":
            depth -= 1
            if depth == 0:
                break
        i += 1
    body = text[start + 1 : i]

    out, depth, buf = [], 0, ""
    for ch in body:
        if ch == "{":
            depth += 1
        if depth > 0:
            buf += ch
        if ch == "}":
            depth -= 1
            if depth == 0:
                out.append(buf)
                buf = ""
    return out


def field(record: str, name: str):
    """One field's value: string, number or boolean. Handles wrapped strings."""
    m = re.search(rf'\b{name}:\s*"((?:[^"\\]|\\.)*)"', record, re.S)
    if m:
        return m.group(1).replace('\\"', '"').replace("\\n", " ")
    m = re.search(rf"\b{name}:\s*\n?\s*\"((?:[^\"\\]|\\.)*)\"", record, re.S)
    if m:
        return m.group(1)
    m = re.search(rf"\b{name}:\s*(true|false)\b", record)
    if m:
        return m.group(1) == "true"
    m = re.search(rf"\b{name}:\s*(-?[\d.]+)", record)
    if m:
        v = float(m.group(1))
        return int(v) if v.is_integer() else v
    return None


def read(name: str) -> str:
    return (SRC / name).read_text()


# ---------------------------------------------------------------- reference
def reference_sql() -> tuple[str, dict]:
    counts = {}
    lines = [
        "-- GENERATED by scripts/build-supabase-sql.py — do not edit by hand.",
        "--",
        "-- Reference data: the things you set up once and then edit as the",
        "-- programme changes. Every row here is editable; nothing about the",
        "-- checklist, the categories or the weights is compiled into the app.",
        "",
        "begin;",
        "",
    ]

    # SHEW pillars
    dom = read("domains.ts")
    rows = records(dom, "DOMAINS")
    counts["domains"] = len(rows)
    lines.append("-- SHEW pillars, used to tag questions and hazards.")
    lines.append("insert into shew_domains (id, label, is_shew, description) values")
    vals = [
        f"  ({q(field(r,'id'))}, {q(field(r,'label'))}, "
        f"{q(bool(field(r,'shew')))}, {q(field(r,'description'))})"
        for r in rows
    ]
    lines.append(",\n".join(vals) + "\non conflict (id) do nothing;\n")

    # Disciplines
    dis = read("disciplines.ts")
    rows = records(dis, "DISCIPLINES")
    counts["disciplines"] = len(rows)
    lines.append("-- The five scorecard disciplines and their weights.")
    lines.append(
        "insert into disciplines (id, name, short_name, weight, has_checklist) values"
    )
    vals = [
        f"  ({q(field(r,'id'))}, {q(field(r,'name'))}, {q(field(r,'shortName'))}, "
        f"{q(field(r,'weight'))}, {q(bool(field(r,'detailed')))})"
        for r in rows
    ]
    lines.append(",\n".join(vals) + "\non conflict (id) do nothing;\n")

    # Rating bands
    ban = read("bands.ts")
    rows = records(ban, "BANDS")
    counts["bands"] = len(rows)
    lines.append("-- Rating bands. min_score is the floor, inclusive.")
    lines.append("insert into rating_bands (id, label, min_score, shown_as) values")
    vals = [
        f"  ({q(field(r,'id'))}, {q(field(r,'label'))}, {q(field(r,'min'))}, "
        f"{q(field(r,'range'))})"
        for r in rows
    ]
    lines.append(",\n".join(vals) + "\non conflict (id) do nothing;\n")

    # Issue categories
    iss = read("issues.ts")
    rows = records(iss, "ISSUE_CATEGORIES")
    counts["issue_categories"] = len(rows)
    lines.append("-- Why a requirement was not met. Multi-select on a finding.")
    lines.append(
        "insert into issue_categories (code, label, description, owner, is_gap, sort) values"
    )
    vals = [
        f"  ({q(field(r,'code'))}, {q(field(r,'label'))}, {q(field(r,'description'))}, "
        f"{q(field(r,'owner'))}, {q(bool(field(r,'gap')))}, {i})"
        for i, r in enumerate(rows)
    ]
    lines.append(",\n".join(vals) + "\non conflict (code) do nothing;\n")

    # Critical risks
    crc = read("critical-risks.ts")
    rows = records(crc, "CRITICAL_RISKS")
    counts["critical_risks"] = len(rows)
    lines.append("-- The Critical Risk Control hazardous-work register.")
    lines.append(
        "insert into critical_risks (id, label, domain_id, sort) values"
    )
    vals = [
        f"  ({q(field(r,'id'))}, {q(field(r,'label'))}, {q(field(r,'domain'))}, {i})"
        for i, r in enumerate(rows)
    ]
    lines.append(",\n".join(vals) + "\non conflict (id) do nothing;\n")

    lines.append("commit;")
    return "\n".join(lines) + "\n", counts


# ---------------------------------------------------------------- checklist
def checklist_sql() -> tuple[str, dict]:
    text = read("checklist.ts")
    lines = [
        "-- GENERATED by scripts/build-supabase-sql.py — do not edit by hand.",
        "--",
        "-- The 81-question Health & Safety checklist. Editable: change a",
        "-- weight or a question here and the app follows, because it reads",
        "-- the checklist from this table rather than carrying its own copy.",
        "",
        "begin;",
        "",
        "insert into checklist_sections (code, title, sort) values",
    ]

    sections, subsections, questions = [], [], []
    sec_sort = 0
    for sec in re.finditer(
        r'\{\s*code:\s*"([A-C])",\s*title:\s*"([^"]*)",\s*subSections:\s*\[(.*?)\]\s*\},?\s*(?=\{\s*code:\s*"[A-C]"|\]\s*;)',
        text,
        re.S,
    ):
        sec_code, sec_title, body = sec.group(1), sec.group(2), sec.group(3)
        sections.append((sec_code, sec_title, sec_sort))
        sec_sort += 1
        sub_sort = 0
        for sub in re.finditer(
            r'\{\s*code:\s*(null|"[^"]*"),\s*title:\s*(null|"[^"]*"),\s*questions:\s*\[(.*?)\]\s*\}',
            body,
            re.S,
        ):
            raw_code, raw_title, qbody = sub.group(1), sub.group(2), sub.group(3)
            sub_code = None if raw_code == "null" else raw_code.strip('"')
            sub_title = None if raw_title == "null" else raw_title.strip('"')
            subsections.append((sec_code, sub_code, sub_title, sub_sort))
            sub_sort += 1
            q_sort = 0
            for qm in re.finditer(
                r'\{\s*code:\s*"([^"]+)",\s*weight:\s*(\d+),\s*text:\s*"((?:[^"\\]|\\.)*)"\s*,\s*domain:\s*"([^"]+)"\s*\}',
                qbody,
                re.S,
            ):
                questions.append(
                    (
                        qm.group(1),
                        sec_code,
                        sub_code,
                        int(qm.group(2)),
                        qm.group(3).replace('\\"', '"'),
                        qm.group(4),
                        q_sort,
                    )
                )
                q_sort += 1

    lines.append(
        ",\n".join(f"  ({q(c)}, {q(t)}, {s})" for c, t, s in sections)
        + "\non conflict (code) do nothing;\n"
    )
    lines.append(
        "-- Section A's questions sit directly in the section, so its"
        "\n-- sub-section has no code; it is still a checklist AREA."
    )
    lines.append(
        "insert into checklist_subsections (section_code, code, title, sort) values"
    )
    lines.append(
        ",\n".join(
            f"  ({q(sc)}, {q(cc)}, {q(ct)}, {s})" for sc, cc, ct, s in subsections
        )
        + "\non conflict do nothing;\n"
    )
    lines.append(
        "insert into checklist_questions\n"
        "  (code, section_code, subsection_code, weight, question, domain_id, sort) values"
    )
    lines.append(
        ",\n".join(
            f"  ({q(c)}, {q(sec)}, {q(sub)}, {w}, {q(txt)}, {q(dom)}, {s})"
            for c, sec, sub, w, txt, dom, s in questions
        )
        + "\non conflict (code) do nothing;\n"
    )
    lines.append("commit;")
    return "\n".join(lines) + "\n", {
        "sections": len(sections),
        "subsections": len(subsections),
        "questions": len(questions),
    }


# ------------------------------------------------------- contractors/audits
def dataset_sql() -> tuple[str, str, dict]:
    text = read("recorded.ts")
    subs = re.findall(r'\{ id: "(\w+)", name: "([^"]*)" \}', text)
    contractors = re.findall(
        r'\{ id: "(\w+)", code: "([^"]+)", name: "([^"]+)",'
        r' subRegionId: "(\w+)", active: (true|false) \}',
        text,
    )

    audits = []
    for m in re.finditer(r"\{\s*id: \"([^\"]+)\",(.*?)\n  \},", text, re.S):
        body = m.group(2)
        get = lambda n: (re.search(rf'{n}: "([^"]+)"', body) or [None, None])[1]
        rt = re.search(r"reportedTotal: ([\d.]+)", body)
        areas = re.findall(
            r"(\w+): \{ scored: ([\d.]+), possible: ([\d.]+) \}", body
        )
        audits.append(
            {
                "key": m.group(1),
                "contractor": get("contractorId"),
                "quarter": get("quarter"),
                "date": get("auditDate"),
                "insp": get("inspectionNo"),
                "reported": float(rt.group(1)) if rt else None,
                "areas": areas,
            }
        )

    ref = [
        "-- GENERATED by scripts/build-supabase-sql.py — do not edit by hand.",
        "--",
        "-- Sub-regions and contractors. Contractors are INITIALS + the last",
        "-- three digits of the work order, and nothing more: that is what",
        "-- keeps this data unidentifying, which is what lets it be hosted",
        "-- outside the Kingdom (docs/COMPLIANCE-KSA.md §4). Do not widen",
        "-- these columns back out to full names or full work orders.",
        "",
        "begin;",
        "",
        "insert into sub_regions (id, name) values",
        ",\n".join(f"  ({q(i)}, {q(n)})" for i, n in subs)
        + "\non conflict (id) do nothing;\n",
        "insert into contractors (id, code, name, sub_region_id, active) values",
        ",\n".join(
            f"  ({q(i)}, {q(c)}, {q(n)}, {q(sr)}, {a})"
            for i, c, n, sr, a in contractors
        )
        + "\non conflict (id) do nothing;\n",
        "commit;",
    ]

    aud = [
        "-- GENERATED by scripts/build-supabase-sql.py — do not edit by hand.",
        "--",
        "-- OPTIONAL. The 19 real Health & Safety audits for Q4 2025 and",
        "-- Q1 2026, verified cell by cell against HS_AUDIT_FINDINGS.xlsx",
        "-- (scripts/verify-against-sheet.py). Run this if you want the two",
        "-- quarters already loaded; skip it to start from an empty system",
        "-- and enter everything by hand.",
        "--",
        "-- These audits hold AREA points and no per-question answers: the",
        "-- source sheets recorded a written note per question and never a",
        "-- Full/Partial/No, so there is nothing honest to put in",
        "-- audit_responses for them.",
        "",
        "begin;",
        "",
    ]
    for a in audits:
        aud.append(
            f"insert into audits (contractor_id, quarter, audit_date, "
            f"inspection_no, status, reported_total)\nvalues ({q(a['contractor'])}, "
            f"{q(a['quarter'])}, {q(a['date'])}, {q(a['insp'])}, 'approved', "
            f"{q(a['reported'])})\non conflict (contractor_id, quarter) do nothing;"
        )
        vals = ",\n".join(
            f"    ((select id from audits where contractor_id = {q(a['contractor'])} "
            f"and quarter = {q(a['quarter'])}), {q(code)}, {scored}, {possible})"
            for code, scored, possible in a["areas"]
        )
        aud.append(
            "insert into audit_area_scores (audit_id, area_code, scored, possible) values\n"
            + vals
            + "\non conflict (audit_id, area_code) do nothing;\n"
        )
    aud.append("commit;")

    return (
        "\n".join(ref) + "\n",
        "\n".join(aud) + "\n",
        {"sub_regions": len(subs), "contractors": len(contractors), "audits": len(audits)},
    )


def main() -> int:
    (OUT / "migrations").mkdir(parents=True, exist_ok=True)

    checklist, c1 = checklist_sql()
    reference, c2 = reference_sql()
    contractors, audits, c3 = dataset_sql()

    (OUT / "migrations" / "0002_reference_data.sql").write_text(reference)
    (OUT / "migrations" / "0003_checklist.sql").write_text(checklist)
    (OUT / "migrations" / "0004_contractors.sql").write_text(contractors)
    (OUT / "seed_audits_2025Q4_2026Q1.sql").write_text(audits)

    counts = {**c1, **c2, **c3}
    expected = {
        "questions": 81, "sections": 3, "subsections": 15,
        "issue_categories": 13, "critical_risks": 14, "disciplines": 5,
        "bands": 5, "domains": 6, "contractors": 13, "audits": 19,
        "sub_regions": 2,
    }
    bad = {k: (counts.get(k), v) for k, v in expected.items() if counts.get(k) != v}
    for k, v in sorted(counts.items()):
        print(f"  {k:18} {v}", file=sys.stderr)
    if bad:
        for k, (got, want) in bad.items():
            print(f"  MISMATCH {k}: parsed {got}, expected {want}", file=sys.stderr)
        return 1
    print("  all counts match the app's own data", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
